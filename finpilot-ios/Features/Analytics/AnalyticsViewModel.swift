import SwiftUI

@Observable
@MainActor
public final class AnalyticsViewModel {
    public var transactions: [Transaction] = []
    public var referenceDate: Date = Date()
    public var isLoading: Bool = false
    public var errorMessage: String?

    public var monthlySummary: MonthlySummary {
        AnalyticsCalculator.calculateMonthlySummary(transactions: transactions, for: referenceDate)
    }

    public var categoryBreakdown: [CategorySpending] {
        AnalyticsCalculator.calculateCategoryBreakdown(transactions: transactions, for: referenceDate)
    }

    public var dailyTrend: [DailySpendingPoint] {
        AnalyticsCalculator.calculateDailySpendingTrend(transactions: transactions, for: referenceDate)
    }

    public var monthOverMonth: MonthOverMonthComparison {
        AnalyticsCalculator.compareMonthOverMonth(transactions: transactions, referenceDate: referenceDate)
    }

    public var shareableSummaryText: String {
        let cur = monthlySummary
        let mom = monthOverMonth
        return """
        📊 FinPilot Monthly Financial Summary: \(AppDateFormatters.fullMonthYear.string(from: referenceDate))
        • Total Income: ₹\(Int(cur.totalIncome))
        • Total Expenses: ₹\(Int(cur.totalExpense))
        • Net Savings: ₹\(Int(cur.netSavings)) (\(Int(cur.savingsRate * 100))% savings rate)
        • Month-over-Month Outflow: \(mom.isIncrease ? "+" : "-")\(Int(abs(mom.percentageChange)))% vs last month.

        Generated by FinPilot — AI Personal Finance Coach
        """
    }

    private let transactionRepository: TransactionRepositoryProtocol

    public init(transactionRepository: TransactionRepositoryProtocol) {
        self.transactionRepository = transactionRepository
    }

    public func loadData() async {
        isLoading = true
        errorMessage = nil
        do {
            self.transactions = try await transactionRepository.getTransactions()
        } catch {
            errorMessage = "Failed to load analytics: \(error.localizedDescription)"
        }
        isLoading = false
    }

    public func previousMonth() {
        if let prev = Calendar.current.date(byAdding: .month, value: -1, to: referenceDate) {
            referenceDate = prev
            FPHaptics.light()
        }
    }

    public func nextMonth() {
        if let next = Calendar.current.date(byAdding: .month, value: 1, to: referenceDate) {
            referenceDate = next
            FPHaptics.light()
        }
    }
}
